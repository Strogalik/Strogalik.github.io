// Preserve existing local resources. The clean source release deliberately excludes binaries.
// Missing resources use the already pinned, locally installed @fontsource packages.
import {access,writeFile,readFile} from 'node:fs/promises';
const local=await Promise.all(['public/fonts/Inter.woff2','public/fonts/Montserrat.woff2'].map(p=>access(p).then(()=>true,()=>false)));
const useLocal=local.every(Boolean)&&process.env.FONTS_FROM_NPM!=='1';
const code=useLocal?`// Generated by scripts/prepare-fonts.mjs; original local fonts remain unchanged.
import localFont from 'next/font/local';
const inter=localFont({src:'../public/fonts/Inter.woff2',variable:'--font-inter',display:'swap',weight:'400 700'});
const montserrat=localFont({src:'../public/fonts/Montserrat.woff2',variable:'--font-montserrat',display:'swap',weight:'700'});
export const fontClass=\x60\x24{inter.variable} \x24{montserrat.variable}\x60;
`:`// Generated fallback for the source ZIP, which excludes binary fonts.
import '@fontsource/inter/400.css';
import '@fontsource/inter/500.css';
import '@fontsource/inter/600.css';
import '@fontsource/inter/700.css';
import '@fontsource/montserrat/700.css';
export const fontClass='tms-npm-fonts';
`;
if(await readFile('app/fonts.ts','utf8').catch(()=>'')!==code)await writeFile('app/fonts.ts',code);
console.log(useLocal?'Fonts: preserved original local WOFF2':'Fonts: pinned @fontsource fallback, no remote font request');
